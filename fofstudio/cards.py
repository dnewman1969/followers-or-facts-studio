"""Cards drawn with Pillow in the channel's colors: quotes, titles, credits,
the "AI illustration" label, and YouTube thumbnails. Text is never generated by
an image model, so a quote on screen is always exactly the verified text."""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont, ImageOps

from .config import REPO, settings

NAVY = (44, 62, 107)
STUDIO = (18, 20, 28)
CREAM = (245, 240, 230)
GOLD = (212, 160, 23)
WHITE = (255, 255, 255)
RED = (192, 57, 43)

OWL = REPO / "brand" / "owlbert-profile.png"

_CANDIDATES = {
    "serif": ["C:/Windows/Fonts/georgia.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSerif.ttf"],
    "serif_bold": ["C:/Windows/Fonts/georgiab.ttf",
                   "/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf"],
    "sans": ["C:/Windows/Fonts/segoeui.ttf", "C:/Windows/Fonts/arial.ttf",
             "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"],
    "sans_bold": ["C:/Windows/Fonts/segoeuib.ttf", "C:/Windows/Fonts/arialbd.ttf",
                  "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"],
}


@lru_cache(maxsize=64)
def font(kind: str, size: int) -> ImageFont.FreeTypeFont:
    override = settings()["paths"].get("font_bold" if kind.endswith("bold") else "font_regular")
    for path in ([override] if override else []) + _CANDIDATES[kind]:
        if path and Path(path).exists():
            return ImageFont.truetype(path, size)
    return ImageFont.load_default(size)


@lru_cache(maxsize=1)
def owl() -> Image.Image | None:
    """The mascot with its square studio background keyed out to transparent."""
    if not OWL.exists():
        return None
    img = Image.open(OWL).convert("RGBA")
    bg = img.getpixel((2, 2))
    px = img.load()
    w, h = img.size
    # flood from the edges so dark parts inside the owl are kept
    from collections import deque
    seen = set()
    q = deque([(x, y) for x in range(w) for y in (0, h - 1)] + [(x, y) for x in (0, w - 1) for y in range(h)])
    while q:
        x, y = q.popleft()
        if (x, y) in seen or not (0 <= x < w and 0 <= y < h):
            continue
        seen.add((x, y))
        r, g, b, a = px[x, y]
        if abs(r - bg[0]) + abs(g - bg[1]) + abs(b - bg[2]) > 60:
            continue
        px[x, y] = (r, g, b, 0)
        q.extend(((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)))
    return img.crop(img.getbbox() or (0, 0, w, h))


def _wrap(draw: ImageDraw.ImageDraw, text: str, fnt, max_width: int) -> list[str]:
    words, lines, line = text.split(), [], ""
    for w in words:
        trial = f"{line} {w}".strip()
        if draw.textlength(trial, font=fnt) <= max_width or not line:
            line = trial
        else:
            lines.append(line)
            line = w
    if line:
        lines.append(line)
    return lines


def _fit(draw, text: str, kind: str, max_width: int, max_height: int, start: int, minimum: int = 28):
    size = start
    while size > minimum:
        fnt = font(kind, size)
        lines = _wrap(draw, text, fnt, max_width)
        height = len(lines) * int(size * 1.3)
        if height <= max_height:
            return fnt, lines, size
        size -= 4
    fnt = font(kind, minimum)
    return fnt, _wrap(draw, text, fnt, max_width), minimum


def _background(w: int, h: int) -> Image.Image:
    img = Image.new("RGB", (w, h), STUDIO)
    glow = Image.new("RGB", (w, h), NAVY)
    mask = Image.new("L", (w, h), 0)
    ImageDraw.Draw(mask).ellipse((-w // 3, -h // 2, w * 4 // 3, h * 3 // 2), fill=110)
    mask = mask.filter(ImageFilter.GaussianBlur(w // 8))
    return Image.composite(glow, img, mask)


def quote_card(text: str, attribution: str, out: Path, size=(1920, 1080)) -> Path:
    w, h = size
    img = _background(w, h)
    d = ImageDraw.Draw(img)
    d.rectangle((int(w * .08), int(h * .2), int(w * .08) + 10, int(h * .8)), fill=GOLD)
    fnt, lines, fs = _fit(d, f"\u201c{text}\u201d", "serif", int(w * .74), int(h * .5), 76)
    y = int(h * .5) - len(lines) * int(fs * 1.3) // 2 - 30
    for ln in lines:
        d.text((int(w * .13), y), ln, font=fnt, fill=CREAM)
        y += int(fs * 1.3)
    d.text((int(w * .13), y + 30), f"\u2014 {attribution}", font=font("sans_bold", 40), fill=GOLD)
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)
    return out


def title_card(text: str, out: Path, size=(1920, 1080), kicker: str = "") -> Path:
    w, h = size
    img = _background(w, h)
    d = ImageDraw.Draw(img)
    fnt, lines, fs = _fit(d, text, "serif_bold", int(w * .8), int(h * .45), 110)
    total = len(lines) * int(fs * 1.25)
    y = (h - total) // 2
    if kicker:
        k = font("sans_bold", 36)
        d.text(((w - d.textlength(kicker.upper(), font=k)) / 2, y - 70), kicker.upper(), font=k, fill=GOLD)
    for ln in lines:
        d.text(((w - d.textlength(ln, font=fnt)) / 2, y), ln, font=fnt, fill=WHITE)
        y += int(fs * 1.25)
    d.rectangle(((w - 160) // 2, y + 24, (w + 160) // 2, y + 30), fill=GOLD)
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)
    return out


def credits_card(lines: list[str], credit: str, out: Path, size=(1920, 1080)) -> Path:
    w, h = size
    img = _background(w, h)
    d = ImageDraw.Draw(img)
    d.text((int(w * .07), int(h * .08)), "Sources", font=font("serif_bold", 64), fill=GOLD)
    y = int(h * .19)
    small = font("sans", max(16, h // 36))
    step = int(small.size * 1.45)
    max_w = int(w * .66)
    shown = 0
    for ln in lines:
        if y > int(h * .78):
            break
        text = ln
        while d.textlength(text, font=small) > max_w and len(text) > 10:
            text = text[:-4].rstrip() + "..."
        d.text((int(w * .07), y), f"{shown + 1}. {text}", font=small, fill=CREAM)
        y += step
        shown += 1
    if len(lines) > shown:
        d.text((int(w * .07), y), f"...and {len(lines) - shown} more in the description",
               font=small, fill=CREAM)
    cf, cl, cs = _fit(d, credit, "sans", int(w * .86), 120, 30, 22)
    y = int(h * .86)
    for ln in cl:
        d.text((int(w * .07), y), ln, font=cf, fill=GOLD)
        y += int(cs * 1.3)
    mascot = owl()
    if mascot:
        m = mascot.copy()
        m.thumbnail((int(w * .22), int(h * .5)))
        img.paste(m, (w - m.width - int(w * .05), int(h * .2)), m)
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)
    return out


def ai_label(src: Path, out: Path, text: str = "AI illustration") -> Path:
    img = Image.open(src).convert("RGB")
    d = ImageDraw.Draw(img, "RGBA")
    size = max(18, img.height // 40)
    fnt = font("sans_bold", size)
    pad = size // 2
    tw = d.textlength(text, font=fnt)
    x, y = img.width - tw - pad * 3, img.height - size - pad * 3
    d.rounded_rectangle((x - pad, y - pad // 2, x + tw + pad, y + size + pad), radius=pad,
                        fill=(0, 0, 0, 150))
    d.text((x, y), text, font=fnt, fill=(255, 255, 255, 230))
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)
    return out


def label_overlay(width: int, height: int, out: Path, text: str = "AI illustration") -> Path:
    """Transparent PNG with the label, laid over animated clips by ffmpeg."""
    img = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    size = max(18, height // 40)
    fnt = font("sans_bold", size)
    pad = size // 2
    tw = d.textlength(text, font=fnt)
    x, y = width - tw - pad * 3, height - size - pad * 3
    d.rounded_rectangle((x - pad, y - pad // 2, x + tw + pad, y + size + pad), radius=pad,
                        fill=(0, 0, 0, 150))
    d.text((x, y), text, font=fnt, fill=(255, 255, 255, 230))
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)
    return out


def thumbnail(words: str, out: Path, background: Path | None = None, verdict: str = "FALSE") -> Path:
    """1280x720: owl on the left, at most four big words, a verdict stamp."""
    w, h = 1280, 720
    if background and Path(background).exists():
        img = ImageOps.fit(Image.open(background).convert("RGB"), (w, h))
        img = Image.blend(img, Image.new("RGB", (w, h), STUDIO), 0.55)
    else:
        img = _background(w, h)
    d = ImageDraw.Draw(img)
    mascot = owl()
    if mascot:
        m = mascot.copy()
        m.thumbnail((470, 560))
        img.paste(m, (30, h - m.height - 20), m)
    text = " ".join(words.split()[:4]).upper()
    fnt, lines, fs = _fit(d, text, "sans_bold", 720, 420, 150, 60)
    y = (h - len(lines) * int(fs * 1.05)) // 2 - 30
    for ln in lines:
        x = 520
        d.text((x + 5, y + 5), ln, font=fnt, fill=(0, 0, 0))
        d.text((x, y), ln, font=fnt, fill=WHITE)
        y += int(fs * 1.05)
    if verdict:
        sf = font("sans_bold", 64)
        sw = d.textlength(verdict, font=sf)
        d.rounded_rectangle((520, y + 20, 520 + sw + 40, y + 110), radius=10, fill=RED)
        d.text((540, y + 28), verdict, font=sf, fill=WHITE)
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)
    return out
