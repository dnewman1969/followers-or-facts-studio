@lru_cache(maxsize=64)
def font(kind: str, size: int) -> ImageFont.FreeTypeFont:
    override = settings()["paths"].get("font_bold" if kind.endswith("bold") else "font_regular")
    for path in ([override] if override else []) + _CANDIDATES[kind]:
        if path and Path(path).exists():
            return ImageFont.truetype(path, size)
    return ImageFont.load_default(size)


@lru_cache(maxsize=1)
def owl() -> Image.Image | None:
    """The mascot cut out of its studio background (the same careful cut as the talking puppet,
    which keeps his black cap), cropped to him."""
    if not OWL.exists():
        return None
    from .owl import base
    img = base()
    return img.crop(img.getbbox())


def _wrap(draw: ImageDraw.ImageDraw, text: str, fnt, max_width: int) -> list[str]:
    words, lines, line = text.split(), [], ""
    for w in words:
        trial = f"{line} {w}".strip()
        if draw.textlength(trial, font=fnt) <= max_width or not line:
            line = trial
        else:
            lines.append(line)
            line = w
    if line:
        lines.append(line)
    return lines


def _fit(draw, text: str, kind: str, max_width: int, max_height: int, start: int, minimum: int = 28):
    size = start
    while size > minimum:
        fnt = font(kind, size)
        lines = _wrap(draw, text, fnt, max_width)
        height = len(lines) * int(size * 1.3)
        if height <= max_height:
            return fnt, lines, size
        size -= 4
    fnt = font(kind, minimum)
    return fnt, _wrap(draw, text, fnt, max_width), minimum


# Behind Owlbert: teal, never navy or black, so his black cap and dark-blue feathers stand out
TEAL_TOP = (72, 146, 150)
TEAL_BOTTOM = (24, 78, 90)
SPOT = (250, 228, 176)


def owl_backdrop(w: int, h: int, spot_x: float = 0.25, spot_y: float = 0.55) -> Image.Image:
    """A teal gradient with a warm spotlight where Owlbert stands."""
    grad = Image.linear_gradient("L").resize((w, h))
    img = Image.composite(Image.new("RGB", (w, h), TEAL_BOTTOM), Image.new("RGB", (w, h), TEAL_TOP), grad)
    mask = Image.new("L", (w, h), 0)
    r = int(h * 0.42)
    cx, cy = int(w * spot_x), int(h * spot_y)
    ImageDraw.Draw(mask).ellipse((cx - r, cy - r, cx + r, cy + r), fill=150)
    mask = mask.filter(ImageFilter.GaussianBlur(h // 7))
    return Image.composite(Image.new("RGB", (w, h), SPOT), img, mask)


def _background(w: int, h: int) -> Image.Image:
    img = Image.new("RGB", (w, h), STUDIO)
    glow = Image.new("RGB", (w, h), NAVY)
    mask = Image.new("L", (w, h), 0)
    ImageDraw.Draw(mask).ellipse((-w // 3, -h // 2, w * 4 // 3, h * 3 // 2), fill=110)
    mask = mask.filter(ImageFilter.GaussianBlur(w // 8))
    return Image.composite(glow, img, mask)


def quote_card(text: str, attribution: str, out: Path, size=(1920, 1080)) -> Path:
    w, h = size
    img = _background(w, h)
    d = ImageDraw.Draw(img)
    d.rectangle((int(w * .08), int(h * .2), int(w * .08) + 10, int(h * .8)), fill=GOLD)
    fnt, lines, fs = _fit(d, f"\u201c{text}\u201d", "serif", int(w * .74), int(h * .5), 76)
    y = int(h * .5) - len(lines) * int(fs * 1.3) // 2 - 30
    for ln in lines:
        d.text((int(w * .13), y), ln, font=fnt, fill=CREAM)
        y += int(fs * 1.3)
    d.text((int(w * .13), y + 30), f"\u2014 {attribution}", font=font("sans_bold", 40), fill=GOLD)
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)
    return out


def title_card(text: str, out: Path, size=(1920, 1080), kicker: str = "") -> Path:
    w, h = size
    img = _background(w, h)
    d = ImageDraw.Draw(img)
    fnt, lines, fs = _fit(d, text, "serif_bold", int(w * .8), int(h * .45), 110)
    total = len(lines) * int(fs * 1.25)
    y = (h - total) // 2
    if kicker:
        k = font("sans_bold", 36)
        d.text(((w - d.textlength(kicker.upper(), font=k)) / 2, y - 70), kicker.upper(), font=k, fill=GOLD)
    for ln in lines:
        d.text(((w - d.textlength(ln, font=fnt)) / 2, y), ln, font=fnt, fill=WHITE)
        y += int(fs * 1.25)
    d.rectangle(((w - 160) // 2, y + 24, (w + 160) // 2, y + 30), fill=GOLD)
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)
    return out


def technique_card(name: str, meaning: str, ask: str, out: Path, size=(1920, 1080)) -> Path:
    """Owlbert's "Tell" card: the name of the trick, what it is, and the question to ask next time."""
    w, h = size
    img = owl_backdrop(w, h, 0.18, 0.6)
    d = ImageDraw.Draw(img)
    mascot = owl()
    if mascot:
        m = mascot.copy()
        m.thumbnail((int(w * 0.3), int(h * 0.7)))
        img.paste(m, (int(w * 0.04), h - m.height - int(h * 0.08)), m)
    x0, x1 = int(w * 0.38), int(w * 0.94)
    d.rounded_rectangle((x0 - 40, int(h * 0.14), x1 + 20, int(h * 0.86)), radius=28, fill=(250, 244, 230),
                        outline=GOLD, width=8)
    k = font("sans_bold", max(20, h // 30))
    d.text((x0, int(h * 0.19)), "OWLBERT'S TELL", font=k, fill=(150, 110, 10))
    fnt, lines, fs = _fit(d, name, "serif_bold", x1 - x0, int(h * 0.2), 96, 40)
    y = int(h * 0.26)
    for ln in lines:
        d.text((x0, y), ln, font=fnt, fill=(24, 30, 48))
        y += int(fs * 1.15)
    body = font("sans", max(18, h // 26))
    for ln in _wrap(d, meaning, body, x1 - x0)[:3]:
        d.text((x0, y + 20), ln, font=body, fill=(40, 46, 66))
        y += int(body.size * 1.35)
    ask_f = font("sans_bold", max(18, h // 28))
    y = max(y + 50, int(h * 0.62))
    d.text((x0, y), "ASK:", font=ask_f, fill=(192, 57, 43))
    for ln in _wrap(d, ask, ask_f, x1 - x0 - int(ask_f.size * 3))[:3]:
        d.text((x0 + int(ask_f.size * 2.8), y), ln, font=ask_f, fill=(24, 30, 48))
        y += int(ask_f.size * 1.3)
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)
    return out


def name_caption(src: Path, out: Path, name: str) -> Path:
    """'Caricature: <name>' banner at the top left of a caricature picture (keeps its AI label)."""
    img = Image.open(src).convert("RGB")
    d = ImageDraw.Draw(img, "RGBA")
    size = max(18, img.height // 34)
    fnt = font("sans_bold", size)
    text = f"Caricature: {name}"
    pad = size // 2
    tw = d.textlength(text, font=fnt)
    d.rounded_rectangle((pad * 2, pad * 2, pad * 4 + tw, pad * 4 + size), radius=pad, fill=(192, 57, 43, 220))
    d.text((pad * 3, pad * 3 - 2), text, font=fnt, fill=(255, 255, 255, 255))
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)
    return out


def credits_card(lines: list[str], credit: str, out: Path, size=(1920, 1080)) -> Path:
    w, h = size
    img = _background(w, h)
    d = ImageDraw.Draw(img)
    d.text((int(w * .07), int(h * .08)), "Sources", font=font("serif_bold", 64), fill=GOLD)
    y = int(h * .19)
    small = font("sans", max(16, h // 36))
    step = int(small.size * 1.45)
    max_w = int(w * .66)
    shown = 0
    for ln in lines:
        if y > int(h * .78):
            break
        text = ln
        while d.textlength(text, font=small) > max_w and len(text) > 10:
            text = text[:-4].rstrip() + "..."
        d.text((int(w * .07), y), f"{shown + 1}. {text}", font=small, fill=CREAM)
        y += step
        shown += 1
    if len(lines) > shown:
        d.text((int(w * .07), y), f"...and {len(lines) - shown} more in the description",
               font=small, fill=CREAM)
    cf, cl, cs = _fit(d, credit, "sans", int(w * .86), 120, 30, 22)
    y = int(h * .86)
    for ln in cl:
        d.text((int(w * .07), y), ln, font=cf, fill=GOLD)
        y += int(cs * 1.3)
    mascot = owl()
    if mascot:
        m = mascot.copy()
        m.thumbnail((int(w * .22), int(h * .5)))
        img.paste(m, (w - m.width - int(w * .05), int(h * .2)), m)
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)
    return out


def ai_label(src: Path, out: Path, text: str = "AI illustration") -> Path:
    img = Image.open(src).convert("RGB")
    d = ImageDraw.Draw(img, "RGBA")
    size = max(18, img.height // 40)
    fnt = font("sans_bold", size)
    pad = size // 2
    tw = d.textlength(text, font=fnt)
    x, y = pad * 3, img.height - size - pad * 3  # bottom-left: the owl presenter has bottom-right
    d.rounded_rectangle((x - pad, y - pad // 2, x + tw + pad, y + size + pad), radius=pad,
                        fill=(0, 0, 0, 150))
    d.text((x, y), text, font=fnt, fill=(255, 255, 255, 230))
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)
    return out


def label_overlay(width: int, height: int, out: Path, text: str = "AI illustration") -> Path:
    """Transparent PNG with the label, laid over animated clips by ffmpeg."""
    img = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    size = max(18, height // 40)
    fnt = font("sans_bold", size)
    pad = size // 2
    tw = d.textlength(text, font=fnt)
    x, y = pad * 3, height - size - pad * 3
    d.rounded_rectangle((x - pad, y - pad // 2, x + tw + pad, y + size + pad), radius=pad,
                        fill=(0, 0, 0, 150))
    d.text((x, y), text, font=fnt, fill=(255, 255, 255, 230))
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)
    return out


def thumbnail(words: str, out: Path, background: Path | None = None, verdict: str = "FALSE") -> Path:
    """1280x720: owl on the left, at most four big words, a verdict stamp."""
    w, h = 1280, 720
    if background and Path(background).exists():
        img = ImageOps.fit(Image.open(background).convert("RGB"), (w, h))
        img = Image.blend(img, Image.new("RGB", (w, h), STUDIO), 0.55)
        # a teal pool behind the owl so his cap doesn't vanish into a dark picture
        pool = owl_backdrop(w, h, 0.2, 0.62)
        m = Image.new("L", (w, h), 0)
        ImageDraw.Draw(m).ellipse((-120, 120, 560, 820), fill=230)
        img = Image.composite(pool, img, m.filter(ImageFilter.GaussianBlur(60)))
    else:
        img = owl_backdrop(w, h, 0.2, 0.62)
    d = ImageDraw.Draw(img)
    mascot = owl()
    if mascot:
        m = mascot.copy()
        m.thumbnail((470, 560))
        img.paste(m, (30, h - m.height - 20), m)
    text = " ".join(words.split()[:4]).upper()
    fnt, lines, fs = _fit(d, text, "sans_bold", 720, 420, 150, 60)
    y = (h - len(lines) * int(fs * 1.05)) // 2 - 30
    for ln in lines:
        x = 520
        d.text((x + 5, y + 5), ln, font=fnt, fill=(0, 0, 0))
        d.text((x, y), ln, font=fnt, fill=WHITE)
        y += int(fs * 1.05)
    if verdict:
        sf = font("sans_bold", 64)
        sw = d.textlength(verdict, font=sf)
        d.rounded_rectangle((520, y + 20, 520 + sw + 40, y + 110), radius=10, fill=RED)
        d.text((540, y + 28), verdict, font=sf, fill=WHITE)
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)
    return out
